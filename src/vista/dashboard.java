    /**
     * Compila el código ingresado en el área de texto
     */
    private void compilarCodigo() {
        String codigoFuente = jTextArea1.getText();
        
        if (codigoFuente.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Por favor ingrese código para analizar.", 
                "Advertencia", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String resultado = controlador.analizarCodigoFuente(codigoFuente);
        jTextArea2.setText(resultado);
        jTextArea2.setCaretPosition(0); // Scroll al inicio
    }
    
    /**
     * Muestra la tabla de símbolos del código
     */
    private void mostrarTablaSimbolos() {
        String codigoFuente = jTextArea1.getText();
        
        if (codigoFuente.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, 
                "Por favor ingrese código para analizar.", 
                "Advertencia", 
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String tablaSimbolos = controlador.generarTablaSimbolos(codigoFuente);
        jTextArea2.setText(tablaSimbolos);
        jTextArea2.setCaretPosition(0); // Scroll al inicio
    }

    /**
     * Muestra el resultado del análisis sintáctico del código
     */
    private void mostrarAnalisisSintactico() {
        String codigoFuente = jTextArea1.getText();

        if (codigoFuente.trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "Por favor ingrese código para analizar.",
                "Advertencia",
                JOptionPane.WARNING_MESSAGE);
            return;
        }

        String resultado = controlador.analizarSintaxis(codigoFuente);
        jTextArea2.setText(resultado);
        jTextArea2.setCaretPosition(0); // Scroll al inicio
    }

